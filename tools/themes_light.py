#!/usr/bin/env python3
"""Generates the light themes (1.1.2): CSS variables, picker previews and the
overlay palette, from a hue color, an ink (text) color and two accents."""
import json, sys

def h2c(h): h = h.lstrip('#'); return [int(h[i:i+2], 16) for i in (0, 2, 4)]
def c2h(c): return '#' + ''.join(f'{max(0,min(255,round(x))):02x}' for x in c)
def mix(a, b, f): a, b = h2c(a), h2c(b); return c2h([a[i] + (b[i] - a[i]) * f for i in range(3)])
def rgbs(h): return ', '.join(str(x) for x in h2c(h))

# id: hue (tints backgrounds/lines), ink (text), a1..a4 accents, strong (accent text), fps (overlay FPS)
LIGHT = {
    'light':  dict(hue='#7c5cc4', ink='#1c1530', a=['#7c3aed', '#8b5cf6', '#a855f7', '#c026d3'], strong='#6d28d9'),
    'sky':    dict(hue='#3b82f6', ink='#0f1b33', a=['#1d4ed8', '#2563eb', '#0284c7', '#0891b2'], strong='#1d4ed8'),
    'lagoon': dict(hue='#14b8a6', ink='#0b2a2c', a=['#0f766e', '#0d9488', '#0891b2', '#06b6d4'], strong='#0f766e'),
    'mint':   dict(hue='#10b981', ink='#0f2a1f', a=['#047857', '#059669', '#16a34a', '#65a30d'], strong='#047857'),
    'sand':   dict(hue='#d9a441', ink='#2a1f0e', a=['#c2410c', '#d97706', '#ea580c', '#ca8a04'], strong='#b45309'),
    'rose':   dict(hue='#f43f5e', ink='#2e0f18', a=['#be123c', '#e11d48', '#f43f5e', '#db2777'], strong='#be123c'),
    'paper':  dict(hue='#71717a', ink='#18181b', a=['#334155', '#475569', '#64748b', '#94a3b8'], strong='#334155'),
}

def theme(k, d):
    H, I, a = d['hue'], d['ink'], d['a']
    v = {
        'bg': mix('#ffffff', H, .07), 'bg-rail': '#ffffff', 'panel': '#ffffff', 'panel-2': mix('#ffffff', H, .035),
        'raise': mix('#ffffff', H, .09), 'line': mix('#ffffff', H, .14), 'line-2': mix('#ffffff', H, .24), 'line-3': mix('#ffffff', H, .38),
        'text': I, 'text-2': mix(I, H, .25), 'muted': mix(mix(I, H, .35), '#ffffff', .3), 'faint': mix(mix(I, H, .35), '#ffffff', .52),
        'violet': a[0], 'violet-2': a[0], 'violet-3': d['strong'], 'orchid': a[3],
        'tg-off': mix('#ffffff', H, .22), 'tg-knob': '#ffffff', 'seg-off': mix('#ffffff', H, .13),
    }
    rgb = {
        'a1-rgb': a[0], 'a2-rgb': a[1], 'a3-rgb': a[2], 'a4-rgb': a[3], 'a5-rgb': d['strong'],
        'tint-rgb': mix(I, H, .3), 'panel-rgb': '#ffffff', 'panel2-rgb': v['panel-2'], 'raise-rgb': v['raise'], 'shade-rgb': mix(I, H, .2),
    }
    return v, rgb

def css():
    out = ['/* light themes — generated by tools/themes_light.py (1.1.2) */',
           '[data-tone="light"] {\n  color-scheme: light;\n  --good: #0f9d63; --warn: #b26b00; --bad: #e11d48; --info: #2563eb;\n}']
    for k, d in LIGHT.items():
        v, rgb = theme(k, d)
        body = '; '.join(f'--{n}: {c}' for n, c in v.items()) + ';\n  ' + '; '.join(f'--{n}: {rgbs(c)}' for n, c in rgb.items())
        sh = rgbs(mix(d['ink'], d['hue'], .3))
        out.append(f'[data-theme="{k}"] {{\n  {body};\n  --shadow: 0 18px 50px -24px rgba({sh}, .35);\n}}')
    out.append('[data-tone="light"] .modal-layer, [data-tone="light"] .crop-layer { background: rgba(var(--shade-rgb), .35); }')
    out.append('[data-tone="light"] .scrim { background: rgba(var(--shade-rgb), .25); }')
    out.append('[data-tone="light"] .au-cam, [data-tone="light"] .acct-cam { color: var(--text); }')
    out.append('[data-tone="light"] .auth-bg::after { opacity: .9; }')
    return '\n'.join(out) + '\n'

def previews():
    # rail, bg, panel, a1, a2, text
    return {k: [ '#ffffff', theme(k, d)[0]['bg'], '#ffffff', d['a'][0], d['a'][3], d['ink']] for k, d in LIGHT.items()}

def overlay():
    # bg, line, value, label, unit, fps, acc1, acc2
    res = {}
    for k, d in LIGHT.items():
        v, _ = theme(k, d)
        res[k] = [mix('#ffffff', d['hue'], .05), d['a'][1], d['ink'], mix(d['ink'], d['hue'], .35), mix(mix(d['ink'], d['hue'], .35), '#ffffff', .25), d['strong'], d['a'][0], d['a'][3]]
    return res

if __name__ == '__main__':
    what = sys.argv[1]
    if what == 'css': print(css(), end='')
    elif what == 'pv': print(json.dumps(previews()))
    elif what == 'ov': print(json.dumps(overlay()))
